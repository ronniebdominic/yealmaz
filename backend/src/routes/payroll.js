// Ye-Almaz — Payroll Routes
// netPay = baseSalarySnapshot + sum(adjustments), rounded to 2dp at every
// write (stricter than Payment.amount elsewhere in this codebase — this is
// the most financially sensitive part of the app, so it gets the extra
// rigor). No automatic tax/pension deduction is ever computed.
//
// Phase 2: run-creation now auto-generates PayrollAdjustment rows from
// whatever's already in the system for that period — the employee's
// active Salary Structure (allowances/deductions), APPROVED overtime,
// ACTIVE advance/loan installments, and FINANCE_APPROVED expense claims —
// rather than leaving every one of those as a separate manual step. HR can
// still add/see manual adjustments on top; auto-generated ones are flagged
// (autoGenerated: true) so the two are never confused in the UI.
//
// Generating a run has no side effects: each auto line records the records it
// covers in sourceIds, and those are only marked paid (overtime PAID, advance
// balance reduced, claim REIMBURSED, award PAID) when the run moves to PAID.
// Until APPROVED a run can be regenerated (late approvals, new hires, salary
// changes) or deleted; moving to APPROVED checks nothing it covers has been
// paid elsewhere since.
const express = require('express');
const { protect, restrict } = require('../middleware/auth');
const { appCache, invalidate } = require('../cache');
const { resolveActiveSalaryStructure, computeStructureLines } = require('../services/salaryStructure');

const router = express.Router();
const prisma = require('../db');

const round2 = (n) => Math.round((n + Number.EPSILON) * 100) / 100;

// Sequential workflow — advancing only ever moves one step forward.
// FINALIZED is the terminal "Closed" state (kept as FINALIZED rather than
// renamed, to avoid an enum-value migration for the Phase 1 rows already
// using it).
const WORKFLOW = ['DRAFT', 'PROCESSING', 'REVIEW', 'APPROVED', 'PAID', 'FINALIZED'];
// Manual adjustments, regenerating and deleting are only allowed before a run
// is APPROVED — once approved, changing numbers needs a new correction, not a
// silent edit.
const ADJUSTABLE_STATUSES = ['DRAFT', 'PROCESSING', 'REVIEW'];

class PayrollConflict extends Error {}

async function buildAutoAdjustments(tx, emp, periodMonth, periodYear, from, to) {
  const lines = []; // { label, amount, type, sourceIds }
  const baseSalary = emp.employeeProfile?.baseSalary || 0;

  // 1 + 2. Salary structure (allowances/deductions) and overtime — priced
  // via a PER_OVERTIME_HOUR structure component if one exists (that line
  // carries the OvertimeRecord ids, marked PAID with the run), otherwise
  // surfaced as an informational 0-amount line so unpriced overtime is
  // visible rather than silently dropped.
  const structure = await resolveActiveSalaryStructure(tx, emp.id, to);
  const approvedOt = await tx.overtimeRecord.findMany({ where: { userId: emp.id, date: { gte: from, lte: to }, approvalStatus: 'APPROVED', payrollStatus: 'UNPAID' } });
  const totalOtHours = approvedOt.reduce((s, r) => s + r.overtimeHours, 0);
  const otComponentIds = new Set((structure?.items || []).filter(i => i.component.calcType === 'PER_OVERTIME_HOUR').map(i => i.componentId));

  if (structure) {
    // unitsProduced has no reliable per-employee source in this system yet
    // (case units aren't individually attributed) — PER_UNIT components
    // resolve to 0 rather than a fabricated number.
    const structureLines = computeStructureLines({ structure, baseSalary, approvedOvertimeHours: totalOtHours, unitsProduced: 0 });
    for (const l of structureLines) {
      if (l.amount === 0) continue;
      if (otComponentIds.has(l.componentId)) {
        lines.push({ label: `${l.label} (${totalOtHours}h)`, amount: l.amount, type: 'OVERTIME', sourceIds: approvedOt.map(r => r.id) });
      } else {
        lines.push({ label: l.label, amount: l.amount, type: l.category === 'DEDUCTION' ? 'DEDUCTION' : 'ALLOWANCE' });
      }
    }
  }
  if (!otComponentIds.size && totalOtHours > 0) {
    lines.push({ label: `Overtime (${totalOtHours}h, no rate configured — 0 Br)`, amount: 0, type: 'OVERTIME' });
  }

  // 3. Active advance/loan installment
  const advances = await tx.employeeAdvance.findMany({ where: { userId: emp.id, status: 'ACTIVE', outstandingBalance: { gt: 0 } } });
  for (const adv of advances) {
    const due = round2(Math.min(adv.installmentAmount, adv.outstandingBalance));
    if (due > 0) lines.push({ label: `${adv.type === 'LOAN' ? 'Loan' : 'Advance'} repayment`, amount: -due, type: 'ADVANCE_REPAYMENT', sourceIds: [adv.id] });
  }

  // 4. Finance-approved, not-yet-reimbursed expense claims
  const claims = await tx.expenseClaim.findMany({ where: { userId: emp.id, status: 'FINANCE_APPROVED' } });
  for (const c of claims) {
    lines.push({ label: `Expense reimbursement — ${c.category}`, amount: round2(c.amount), type: 'REIMBURSEMENT', sourceIds: [c.id] });
  }

  // 5. Approved incentive awards for this exact period, not yet paid
  const awards = await tx.incentiveAward.findMany({ where: { userId: emp.id, periodMonth, periodYear, status: 'APPROVED' }, include: { rule: true } });
  for (const a of awards) {
    if (a.awardedAmount > 0) lines.push({ label: `Incentive — ${a.rule.name}`, amount: round2(a.awardedAmount), type: 'INCENTIVE', sourceIds: [a.id] });
  }

  return lines;
}

const periodRange = (month, year) => ({
  from: new Date(year, month - 1, 1),
  to: new Date(year, month, 0, 23, 59, 59, 999),
});

const payrollEmployees = () => prisma.user.findMany({
  where: { isActive: true, employeeProfile: { employmentStatus: 'ACTIVE' } },
  include: { employeeProfile: true },
});

// Writes one employee's entry for a run: fresh base salary snapshot and auto
// lines, keeping any manual adjustments already on an existing entry.
async function writeEntry(tx, run, emp, existing, addedById) {
  const { from, to } = periodRange(run.periodMonth, run.periodYear);
  const baseSalarySnapshot = round2(emp.employeeProfile.baseSalary || 0);
  const autoLines = await buildAutoAdjustments(tx, emp, run.periodMonth, run.periodYear, from, to);
  const manualTotal = (existing?.adjustments || []).filter(a => !a.autoGenerated).reduce((s, a) => s + a.amount, 0);
  const netPay = round2(baseSalarySnapshot + manualTotal + autoLines.reduce((s, l) => s + l.amount, 0));

  const entry = existing
    ? await tx.payrollEntry.update({ where: { id: existing.id }, data: { baseSalarySnapshot, netPay } })
    : await tx.payrollEntry.create({ data: { runId: run.id, userId: emp.id, baseSalarySnapshot, netPay } });

  if (autoLines.length) {
    await tx.payrollAdjustment.createMany({
      data: autoLines.map(l => ({ entryId: entry.id, label: l.label, amount: l.amount, type: l.type, sourceIds: l.sourceIds || [], autoGenerated: true, addedById })),
    });
  }
}

// Runs generated before sourceIds existed paid things out at creation time.
// Regenerating or deleting one would orphan those links, so refuse.
async function hasLegacyPayouts(runId) {
  const entryIds = (await prisma.payrollEntry.findMany({ where: { runId }, select: { id: true } })).map(e => e.id);
  if (!entryIds.length) return false;
  const [claims, awards, repayments] = await Promise.all([
    prisma.expenseClaim.count({ where: { reimbursedInPayrollEntryId: { in: entryIds } } }),
    prisma.incentiveAward.count({ where: { payrollEntryId: { in: entryIds } } }),
    prisma.advanceRepayment.count({ where: { payrollEntryId: { in: entryIds } } }),
  ]);
  return claims + awards + repayments > 0;
}

const sourceLines = (tx, runId) => tx.payrollAdjustment.findMany({
  where: { entry: { runId }, autoGenerated: true, NOT: { sourceIds: { isEmpty: true } } },
  include: { entry: { include: { user: { select: { name: true } } } } },
});

// Before APPROVED: everything the run pays out must still be unpaid and not
// already claimed by another APPROVED (approved but not yet paid) run.
// Returns a list of problems, empty when the run is safe to approve.
async function findSourceConflicts(runId) {
  const lines = await sourceLines(prisma, runId);
  if (!lines.length) return [];
  const allIds = lines.flatMap(l => l.sourceIds);
  const otherLines = await prisma.payrollAdjustment.findMany({
    where: { sourceIds: { hasSome: allIds }, entry: { run: { status: 'APPROVED', id: { not: runId } } } },
    select: { sourceIds: true, amount: true, type: true },
  });
  const claimedElsewhere = new Set(otherLines.filter(l => l.type !== 'ADVANCE_REPAYMENT').flatMap(l => l.sourceIds));
  const advanceDueElsewhere = {};
  for (const l of otherLines.filter(l => l.type === 'ADVANCE_REPAYMENT')) {
    advanceDueElsewhere[l.sourceIds[0]] = (advanceDueElsewhere[l.sourceIds[0]] || 0) - l.amount;
  }

  const problems = [];
  for (const l of lines) {
    const who = `${l.entry.user.name}: ${l.label}`;
    if (l.type === 'ADVANCE_REPAYMENT') {
      const adv = await prisma.employeeAdvance.findUnique({ where: { id: l.sourceIds[0] } });
      const due = -l.amount + (advanceDueElsewhere[l.sourceIds[0]] || 0);
      if (!adv || adv.status !== 'ACTIVE' || round2(adv.outstandingBalance - due) < 0) problems.push(`${who} — balance is lower than this deduction`);
      continue;
    }
    if (l.sourceIds.some(id => claimedElsewhere.has(id))) { problems.push(`${who} — already in another approved run`); continue; }
    const stillPending =
      l.type === 'OVERTIME'      ? await prisma.overtimeRecord.count({ where: { id: { in: l.sourceIds }, payrollStatus: 'UNPAID' } }) :
      l.type === 'REIMBURSEMENT' ? await prisma.expenseClaim.count({ where: { id: { in: l.sourceIds }, status: 'FINANCE_APPROVED' } }) :
      l.type === 'INCENTIVE'     ? await prisma.incentiveAward.count({ where: { id: { in: l.sourceIds }, status: 'APPROVED' } }) :
      l.sourceIds.length;
    if (stillPending !== l.sourceIds.length) problems.push(`${who} — already paid elsewhere`);
  }
  return problems;
}

// On PAID: mark everything the run covers as paid out. Any record that was
// paid some other way since approval aborts the whole transaction.
async function applyPayouts(tx, runId) {
  for (const l of await sourceLines(tx, runId)) {
    const who = `${l.entry.user.name}: ${l.label}`;
    if (l.type === 'OVERTIME') {
      const { count } = await tx.overtimeRecord.updateMany({ where: { id: { in: l.sourceIds }, payrollStatus: 'UNPAID' }, data: { payrollStatus: 'PAID' } });
      if (count !== l.sourceIds.length) throw new PayrollConflict(`${who} — overtime was already paid`);
    } else if (l.type === 'ADVANCE_REPAYMENT') {
      const due = round2(-l.amount);
      const adv = await tx.employeeAdvance.findUnique({ where: { id: l.sourceIds[0] } });
      if (!adv || adv.status !== 'ACTIVE' || round2(adv.outstandingBalance - due) < 0) throw new PayrollConflict(`${who} — balance is lower than this deduction`);
      const remaining = round2(adv.outstandingBalance - due);
      await tx.employeeAdvance.update({ where: { id: adv.id }, data: { outstandingBalance: remaining, status: remaining <= 0 ? 'COMPLETED' : 'ACTIVE' } });
      await tx.advanceRepayment.create({ data: { advanceId: adv.id, payrollEntryId: l.entryId, amount: due } });
    } else if (l.type === 'REIMBURSEMENT') {
      const { count } = await tx.expenseClaim.updateMany({ where: { id: { in: l.sourceIds }, status: 'FINANCE_APPROVED' }, data: { status: 'REIMBURSED', reimbursedInPayrollEntryId: l.entryId } });
      if (count !== l.sourceIds.length) throw new PayrollConflict(`${who} — claim was already reimbursed`);
    } else if (l.type === 'INCENTIVE') {
      const { count } = await tx.incentiveAward.updateMany({ where: { id: { in: l.sourceIds }, status: 'APPROVED' }, data: { status: 'PAID', payrollEntryId: l.entryId } });
      if (count !== l.sourceIds.length) throw new PayrollConflict(`${who} — incentive was already paid`);
    }
  }
}

const RUN_TX_OPTIONS = { timeout: 120000, maxWait: 15000 }; // a full run does many sequential queries — Prisma's 5s default aborts it

// ── POST /api/payroll/runs ─────────────────────────────────
router.post('/runs', protect, restrict('HR_MANAGER', 'ADMIN'), async (req, res) => {
  try {
    const { periodMonth, periodYear } = req.body || {};
    const month = parseInt(periodMonth), year = parseInt(periodYear);
    if (!month || month < 1 || month > 12 || !year) {
      return res.status(400).json({ error: 'A valid periodMonth (1-12) and periodYear are required.' });
    }

    const existing = await prisma.payrollRun.findUnique({ where: { periodMonth_periodYear: { periodMonth: month, periodYear: year } } });
    if (existing) return res.status(409).json({ error: `A payroll run already exists for ${month}/${year}.` });

    const employees = await payrollEmployees();
    const missingSalaryCount = employees.filter(e => e.employeeProfile.baseSalary == null).length;

    const run = await prisma.$transaction(async (tx) => {
      const created = await tx.payrollRun.create({
        data: { periodMonth: month, periodYear: year, createdById: req.user.id },
      });
      for (const emp of employees) await writeEntry(tx, created, emp, null, req.user.id);
      return created;
    }, RUN_TX_OPTIONS);

    await invalidate('payroll:runs*', 'dashboard:hr-summary');
    res.status(201).json({ run, employeeCount: employees.length, missingSalaryCount });
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: 'Could not create payroll run.' });
  }
});

// ── POST /api/payroll/runs/:id/regenerate ───────────────────
// Rebuilds a not-yet-approved run from current data: adds employees who
// became active, refreshes base salaries and every auto line (picking up late
// overtime/expense/incentive approvals). Manual adjustments are kept. An
// employee who is no longer active is dropped unless HR added manual lines
// for them (e.g. a final payment).
router.post('/runs/:id/regenerate', protect, restrict('HR_MANAGER', 'ADMIN'), async (req, res) => {
  try {
    const run = await prisma.payrollRun.findUnique({ where: { id: req.params.id } });
    if (!run) return res.status(404).json({ error: 'Payroll run not found.' });
    if (!ADJUSTABLE_STATUSES.includes(run.status)) return res.status(400).json({ error: `This payroll run is ${run.status} — it can no longer be regenerated.` });
    if (await hasLegacyPayouts(run.id)) return res.status(400).json({ error: 'This run already paid out advances, expenses or incentives when it was created, so it cannot be regenerated.' });

    const employees = await payrollEmployees();
    const missingSalaryCount = employees.filter(e => e.employeeProfile.baseSalary == null).length;

    await prisma.$transaction(async (tx) => {
      const entries = await tx.payrollEntry.findMany({ where: { runId: run.id }, include: { adjustments: true } });
      await tx.payrollAdjustment.deleteMany({ where: { entry: { runId: run.id }, autoGenerated: true } });
      const byUser = new Map(entries.map(e => [e.userId, e]));
      const activeIds = new Set(employees.map(e => e.id));

      for (const emp of employees) await writeEntry(tx, run, emp, byUser.get(emp.id), req.user.id);

      for (const e of entries.filter(e => !activeIds.has(e.userId))) {
        const manual = e.adjustments.filter(a => !a.autoGenerated);
        if (manual.length) {
          await tx.payrollEntry.update({ where: { id: e.id }, data: { netPay: round2(e.baseSalarySnapshot + manual.reduce((s, a) => s + a.amount, 0)) } });
        } else {
          await tx.payrollEntry.delete({ where: { id: e.id } });
        }
      }
    }, RUN_TX_OPTIONS);

    await invalidate('payroll:runs*', 'payroll:entries*', 'dashboard:hr-summary');
    res.json({ success: true, employeeCount: employees.length, missingSalaryCount });
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: 'Could not regenerate payroll run.' });
  }
});

// ── DELETE /api/payroll/runs/:id ────────────────────────────
// Only before APPROVED. Nothing has been paid out yet at that point, so
// deleting just removes the run and its lines.
router.delete('/runs/:id', protect, restrict('HR_MANAGER', 'ADMIN'), async (req, res) => {
  try {
    const run = await prisma.payrollRun.findUnique({ where: { id: req.params.id } });
    if (!run) return res.status(404).json({ error: 'Payroll run not found.' });
    if (!ADJUSTABLE_STATUSES.includes(run.status)) return res.status(400).json({ error: `This payroll run is ${run.status} — it can no longer be deleted.` });
    if (await hasLegacyPayouts(run.id)) return res.status(400).json({ error: 'This run already paid out advances, expenses or incentives when it was created, so it cannot be deleted.' });

    await prisma.$transaction([
      prisma.payrollAdjustment.deleteMany({ where: { entry: { runId: run.id } } }),
      prisma.payrollEntry.deleteMany({ where: { runId: run.id } }),
      prisma.payrollRun.delete({ where: { id: run.id } }),
    ]);
    await invalidate('payroll:runs*', 'payroll:entries*', 'dashboard:hr-summary');
    res.json({ success: true });
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: 'Could not delete payroll run.' });
  }
});

