// ── GET /api/payroll/runs/:id ───────────────────────────────
router.get('/runs/:id', protect, restrict('HR_MANAGER', 'ADMIN'), async (req, res) => {
  try {
    const run = await prisma.payrollRun.findUnique({
      where: { id: req.params.id },
      include: {
        createdBy: { select: { name: true } },
        entries: {
          include: { user: { select: { id: true, name: true, email: true } }, adjustments: { orderBy: { createdAt: 'asc' } } },
          orderBy: { createdAt: 'asc' },
        },
      },
    });
    if (!run) return res.status(404).json({ error: 'Payroll run not found.' });
    // Employer-cost summary for the run detail view — gross earnings vs
    // deductions vs net, across all entries.
    let grossEarnings = 0, deductions = 0;
    for (const e of run.entries) {
      grossEarnings += e.baseSalarySnapshot + e.adjustments.filter(a => a.amount > 0).reduce((s, a) => s + a.amount, 0);
      deductions += e.adjustments.filter(a => a.amount < 0).reduce((s, a) => s + a.amount, 0);
    }
    const totalNetPay = round2(run.entries.reduce((s, e) => s + e.netPay, 0));
    res.json({ ...run, totals: { grossEarnings: round2(grossEarnings), deductions: round2(deductions), netPay: totalNetPay } });
  } catch (err) {
    res.status(500).json({ error: 'Could not load payroll run.' });
  }
});

// ── POST /api/payroll/entries/:id/adjustments ───────────────
router.post('/entries/:id/adjustments', protect, restrict('HR_MANAGER', 'ADMIN'), async (req, res) => {
  try {
    const { label, amount, type } = req.body || {};
    if (!label || !label.trim() || amount == null || isNaN(parseFloat(amount))) {
      return res.status(400).json({ error: 'label and amount are required.' });
    }
    const entry = await prisma.payrollEntry.findUnique({ where: { id: req.params.id }, include: { run: true, adjustments: true } });
    if (!entry) return res.status(404).json({ error: 'Payroll entry not found.' });
    if (!ADJUSTABLE_STATUSES.includes(entry.run.status)) return res.status(400).json({ error: `This payroll run is ${entry.run.status} — no further adjustments can be added.` });

    const signedAmount = round2(parseFloat(amount));
    const [, updated] = await prisma.$transaction([
      prisma.payrollAdjustment.create({
        data: { entryId: entry.id, label: label.trim(), amount: signedAmount, type: type || 'OTHER', addedById: req.user.id },
      }),
      prisma.payrollEntry.update({
        where: { id: entry.id },
        data: { netPay: round2(entry.baseSalarySnapshot + entry.adjustments.reduce((s, a) => s + a.amount, 0) + signedAmount) },
        include: { adjustments: true },
      }),
    ]);

    await invalidate('payroll:runs*', 'payroll:entries*');
    res.status(201).json(updated);
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: 'Could not add adjustment.' });
  }
});

// ── PATCH /api/payroll/runs/:id/advance ─────────────────────
// Moves the run exactly one step forward in DRAFT→PROCESSING→REVIEW→
// APPROVED→PAID→FINALIZED. Never skips or goes backward. Approving checks
// nothing the run covers was paid elsewhere; marking PAID pays it all out.
router.patch('/runs/:id/advance', protect, restrict('HR_MANAGER', 'ADMIN'), async (req, res) => {
  try {
    const run = await prisma.payrollRun.findUnique({ where: { id: req.params.id } });
    if (!run) return res.status(404).json({ error: 'Payroll run not found.' });
    const idx = WORKFLOW.indexOf(run.status);
    if (idx === -1 || idx === WORKFLOW.length - 1) return res.status(400).json({ error: `This run is already ${run.status}.` });
    const next = WORKFLOW[idx + 1];

    if (next === 'APPROVED') {
      const problems = await findSourceConflicts(run.id);
      if (problems.length) {
        return res.status(409).json({ error: `Regenerate this run before approving — ${problems.length} line${problems.length === 1 ? ' is' : 's are'} out of date: ${problems.slice(0, 5).join('; ')}${problems.length > 5 ? '; …' : ''}`, problems });
      }
    }

    const updated = await prisma.$transaction(async (tx) => {
      // Guard against a double click / two tabs advancing the same step.
      const { count } = await tx.payrollRun.updateMany({
        where: { id: run.id, status: run.status },
        data: { status: next, ...(next === 'FINALIZED' ? { finalizedAt: new Date() } : {}) },
      });
      if (!count) throw new PayrollConflict('This run was just updated by someone else — refresh and try again.');
      if (next === 'PAID') await applyPayouts(tx, run.id);
      return tx.payrollRun.findUnique({ where: { id: run.id } });
    }, RUN_TX_OPTIONS);

    await invalidate('payroll:runs*', 'payroll:entries*', 'dashboard:hr-summary', 'advances:*', 'expenses:*', 'incentives:*');
    res.json(updated);
  } catch (err) {
    if (err instanceof PayrollConflict) return res.status(409).json({ error: err.message });
    console.error(err);
    res.status(500).json({ error: 'Could not advance payroll run.' });
  }
});

// ── PATCH /api/payroll/runs/:id/finalize ────────────────────
// Kept for backward compatibility (Phase 1 callers). Closes a PAID run only —
// jumping straight from an earlier step would skip approval and payouts.
router.patch('/runs/:id/finalize', protect, restrict('HR_MANAGER', 'ADMIN'), async (req, res) => {
  try {
    const run = await prisma.payrollRun.findUnique({ where: { id: req.params.id } });
    if (!run) return res.status(404).json({ error: 'Payroll run not found.' });
    if (run.status === 'FINALIZED') return res.status(400).json({ error: 'This run is already finalized.' });
    if (run.status !== 'PAID') return res.status(400).json({ error: 'Only a paid run can be closed — move it through Approved and Paid first.' });

    const updated = await prisma.payrollRun.update({
      where: { id: run.id },
      data: { status: 'FINALIZED', finalizedAt: new Date() },
    });
    await invalidate('payroll:runs*', 'payroll:entries*', 'dashboard:hr-summary');
    res.json(updated);
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: 'Could not finalize payroll run.' });
  }
});

// ── GET /api/payroll/summary ────────────────────────────────
// Shared by AdminHR.jsx's own KPIs and AdminDashboard.jsx's HR section,
// same "one endpoint feeds both" trick as dashboard:inventory-summary.
router.get('/summary', protect, restrict('HR_MANAGER', 'ADMIN'), async (req, res) => {
  const cacheKey = 'dashboard:hr-summary';
  const cached = await appCache.get(cacheKey);
  if (cached) return res.json(cached);
  try {
    const [missingProfileCount, currentRun] = await Promise.all([
      prisma.user.count({ where: { isActive: true, isSharedAccount: false, OR: [{ employeeProfile: null }, { employeeProfile: { baseSalary: null } }] } }),
      prisma.payrollRun.findFirst({ orderBy: [{ periodYear: 'desc' }, { periodMonth: 'desc' }] }),
    ]);
    const result = {
      missingProfileCount,
      currentRunStatus: currentRun?.status || null,
      currentRunPeriod: currentRun ? `${currentRun.periodMonth}/${currentRun.periodYear}` : null,
    };
    await appCache.set(cacheKey, result);
    res.json(result);
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: 'Could not load payroll summary.' });
  }
});

